export type Key = keyof (typeof dict)['ru'];

export function useT() {
  const lang = useStore((s) => s.lang);
  return useCallback(
    (key: Key, vars: Record<string, string | number> = {}) =>
      (dict[lang][key] as string).replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? '')),
    [lang]
  );
}

export function useLocale() {
  return useStore((s) => (s.lang === 'ru' ? 'ru-RU' : 'en-US'));
}

export const docTitle = (lang: 'ru' | 'en') => dict[lang].title;
